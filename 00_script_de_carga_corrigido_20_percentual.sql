SET status = 'Emprestado'
WHERE rfid IN (
    SELECT rfid_exemplar
    FROM emprestimo
    WHERE data_devolucao IS NULL
      AND data_prevista_devolucao >= CURDATE()
);

UPDATE exemplar
SET status = 'Em atraso'
WHERE rfid IN (
    SELECT rfid_exemplar
    FROM emprestimo
    WHERE data_devolucao IS NULL
      AND data_prevista_devolucao < CURDATE()
);

-- Conferência de quantidade de registros por tabela.
SELECT 'tipo_obra' AS tabela, COUNT(*) AS total FROM tipo_obra
UNION ALL SELECT 'area_conhecimento', COUNT(*) FROM area_conhecimento
UNION ALL SELECT 'categoria', COUNT(*) FROM categoria
UNION ALL SELECT 'autor', COUNT(*) FROM autor
UNION ALL SELECT 'obra', COUNT(*) FROM obra
UNION ALL SELECT 'obra_autor', COUNT(*) FROM obra_autor
UNION ALL SELECT 'exemplar', COUNT(*) FROM exemplar
UNION ALL SELECT 'tipo_usuario', COUNT(*) FROM tipo_usuario
UNION ALL SELECT 'usuario', COUNT(*) FROM usuario
UNION ALL SELECT 'telefone_usuario', COUNT(*) FROM telefone_usuario
UNION ALL SELECT 'endereco_usuario', COUNT(*) FROM endereco_usuario
UNION ALL SELECT 'emprestimo', COUNT(*) FROM emprestimo
UNION ALL SELECT 'multa', COUNT(*) FROM multa
UNION ALL SELECT 'notificacao', COUNT(*) FROM notificacao;

-- Conferência específica das movimentações.
SELECT
    COUNT(*) AS total_emprestimos,
    SUM(CASE WHEN status = 'Devolvido com atraso' THEN 1 ELSE 0 END) AS emprestimos_com_multa,
    SUM(CASE WHEN status = 'Devolvido' THEN 1 ELSE 0 END) AS emprestimos_sem_multa,
    SUM(CASE WHEN status = 'Emprestado' THEN 1 ELSE 0 END) AS emprestimos_abertos_no_prazo,
    SUM(CASE WHEN status = 'Em atraso' THEN 1 ELSE 0 END) AS emprestimos_abertos_em_atraso
FROM emprestimo;

SELECT
    COUNT(*) AS total_multas,
    SUM(valor) AS soma_valor_multas,
    SUM(desconto) AS soma_descontos,
    SUM(valor - desconto) AS soma_multas_pagas
FROM multa;

SELECT COUNT(*) AS total_notificacoes FROM notificacao;
